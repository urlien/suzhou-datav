// 合并数据（供各模块使用）
export interface DistrictData {
  name: string;
  area: number;
  population: number;
  gdp: number;
  year: string; // 数据年份
}

export function getDistrictData(): DistrictData[] {
  const districts = Object.keys(areaData);
  return districts.map(name => ({
    name,
    area: areaData[name],
    population: populationData[name] || 0,
    gdp: gdpData[name] || 0,
    year: '2024-2025' // 混合年份
  }));
}

